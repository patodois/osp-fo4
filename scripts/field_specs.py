"""Import only explicitly authorized black-box layout facts, never implementation."""
import argparse,csv,json,re
from pathlib import Path
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('fichas',type=Path,help='explicitly authorized xdump/fichas directory')
root=parser.parse_args().fichas
rows=list(csv.DictReader((root/'INDICE.tsv').open(),delimiter='\t'))
facts=[];schemas=[];flag_words=[];q=lambda s:json.dumps(s,ensure_ascii=False)
for r in rows:
 key=r['par'];txt=(root/(key+'.md')).read_text();fields=[]
 sizes=[]
 for line in txt.splitlines():
  a=[c.strip() for c in line.strip('|').split('|')]
  if key in ['LIGH.DATA','CELL.XCLL'] and len(a)==3 and re.fullmatch(r'`[0-9A-Fa-f]{8}`',a[1]):
   raw=int(a[1].strip('`'),16);label=None if a[2]=='rótulo sem valor' else a[2].strip('"')
   flag_words.append((key,raw,label,'Unknown' not in a[2] and (label is not None or raw==0),r['registros_conferidos']))
  if len(a)==8 and a[1].isdigit() and a[2].isdigit():
   label,offset,width,typ,variants,*_=a;variants=[int(s.strip()) for s in variants.split(',')]
   kind='Float' if typ.startswith('f32') else 'Form' if typ.startswith('FormID') else 'I32' if typ.startswith('i32') else 'U32' if typ.startswith('u32') else 'Text' if typ.startswith('texto') else 'Color' if typ.startswith('RGB') else 'Presence' if typ=='presença sem bytes' else 'Bytes'
   fields.append((label,int(offset),int(width),kind,variants))
   facts.append('\t'.join([key,label,offset,width,typ,','.join(map(str,variants)),r['registros_conferidos'],r['estado']]))
  if len(a)>=3 and a[0].isdigit() and a[1].isdigit() and a[2].isdigit():sizes.append(int(a[0]))
 # Not one inferred header layout for MODT, or unverified size.
 sizes=sorted(set(sizes))
 closed=r['estado']=='fechado'
 openfield='Flags.Unknown_0_13_21_and_unmapped_bits' if key=='LIGH.DATA' else 'Inherits.unmapped_bits_and_unused_color_bytes' if key=='CELL.XCLL' else 'layout_not_established'
 fs=',\n'.join('        FieldSpec { label: '+q(label)+f', offset: {o}, width: {w}, kind: Kind::{k}, sizes: &{ss!r}'+' }' for label,o,w,k,ss in fields)
 schemas.append('    Schema { pair: '+q(key)+', sizes: &'+repr(sizes)+', closed: '+str(closed).lower()+', open_field: '+q(openfield)+', fields: &[\n'+fs+'\n    ] }')
Path('spec/record-fichas.tsv').write_text('# RECORD.TAG\tlabel\toffset\tbytes\ttype\tverified_sizes\tchecked_records\tstate\n'+'\n'.join(facts)+'\n')
Path('crates/fo4-plugin/src/ficha_data.rs').write_text('// Layout facts only; generated by scripts/stage14-fichas.py. See spec/record-fichas.md.\nuse super::{FieldSpec, Kind, Schema, FlagWord};\npub(super) const SCHEMAS: &[Schema] = &[\n'+',\n'.join(schemas)+'\n];\n')
with Path('crates/fo4-plugin/src/ficha_data.rs').open('a') as out:
 out.write('pub(super) static FLAG_WORDS: &[FlagWord] = &[\n')
 for pair,raw,label,closed,n in flag_words:
  out.write('    FlagWord { pair: '+q(pair)+', raw: '+str(raw)+', label: '+('None' if label is None else 'Some('+q(label)+')')+', closed: '+str(closed).lower()+' },\n')
 out.write('];\n')
Path('spec/record-flag-words.tsv').write_text('# pair\traw_u32_hex\tprinted_labels\tfully_named\tchecked_records_in_ficha\n'+'\n'.join('\t'.join([pair,f'{raw:08x}',label if label is not None else '(no printed value)',str(closed).lower(),n]) for pair,raw,label,closed,n in flag_words)+'\n')
print('flag words',len(flag_words))
print('schemas',len(schemas),'field facts',len(facts))
